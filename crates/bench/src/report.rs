//! Renders `BENCHMARKS.md` from recorded runs.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::record::{Measurement, Run};

/// How many past runs the history table shows per adapter.
pub const HISTORY_RUNS: usize = 8;

/// Inputs preferred, in order, for a measurement's history row.
const HEADLINE_INPUTS: [&str; 3] = ["silesia/all", "text", "random"];

/// Per-file corpus inputs (`corpus/file`) stay in the JSON; the report keeps
/// synthetic inputs and whole-corpus totals (`corpus/all`).
fn shown(m: &Measurement) -> bool {
    !m.input.contains('/') || m.input.ends_with("/all")
}

fn first_seen<'a>(items: impl Iterator<Item = &'a str>) -> Vec<&'a str> {
    let mut out: Vec<&str> = Vec::new();
    for item in items {
        if !out.contains(&item) {
            out.push(item);
        }
    }
    out
}

/// Renders the short Markdown summary: per adapter, the latest run as a
/// measurement × input matrix, plus a history (measurement × run) of GB/s.
pub fn render(runs: &[Run]) -> String {
    let mut md = String::new();
    let _ = writeln!(md, "# Benchmarks\n");
    let _ = writeln!(
        md,
        "Generated by `gpucomp bench --report` from `bench/results/*.json`; don't edit by hand.  \n\
         Throughput is GB/s (10^9 bytes/s) of uncompressed data, median of several runs; higher is better.  \n\
         Ratio = original size / compressed size. Timing: `gpu-timestamp` = kernel only, \
         `wall-gpu` = submit + wait with data already on the GPU (used when timestamps are unavailable), \
         `wall-e2e` = upload + GPU work + readback, `cpu` = CPU wall clock.\n"
    );

    let mut by_adapter: BTreeMap<&str, Vec<&Run>> = BTreeMap::new();
    for run in runs {
        by_adapter.entry(&run.adapter).or_default().push(run);
    }
    for (adapter, mut runs) in by_adapter {
        runs.sort_by(|a, b| a.date.cmp(&b.date));
        let latest = runs[runs.len() - 1];
        let _ = writeln!(md, "## {adapter} ({})\n", latest.backend);

        let _ = writeln!(
            md,
            "### Latest run — {} · {} · `{}` · {}\n",
            latest.label, latest.date, latest.commit, latest.os
        );
        let rows: Vec<&Measurement> = latest.measurements.iter().filter(|m| shown(m)).collect();
        let inputs = first_seen(rows.iter().map(|m| m.input.as_str()));
        let names = first_seen(rows.iter().map(|m| m.name.as_str()));
        let _ = writeln!(md, "GB/s, with compression ratio where it applies.\n");
        let _ = writeln!(md, "| Measurement | {} | Timing |", inputs.join(" | "));
        let _ = writeln!(md, "|---|{}---|", "---:|".repeat(inputs.len()));
        for name in &names {
            let mut row = format!("| {name} |");
            let mut timing = String::new();
            for input in &inputs {
                let cell = match rows.iter().find(|m| m.name == *name && m.input == *input) {
                    Some(m) => {
                        timing = serde_json::to_string(&m.timing)
                            .unwrap_or_default()
                            .trim_matches('"')
                            .to_string();
                        match m.ratio {
                            Some(r) => format!("{:.2} · {r:.2}×", m.gbps),
                            None => format!("{:.2}", m.gbps),
                        }
                    }
                    None => "—".into(),
                };
                let _ = write!(row, " {cell} |");
            }
            let _ = writeln!(md, "{row} {timing} |");
        }
        let sizes: Vec<String> = inputs
            .iter()
            .filter_map(|i| rows.iter().find(|m| m.input == *i))
            .map(|m| format!("{} {}", m.input, human_bytes(m.bytes)))
            .collect();
        let _ = writeln!(md, "\nInput sizes: {}.", sizes.join(", "));

        // History: one headline input per measurement, across recent runs.
        let recent = &runs[runs.len().saturating_sub(HISTORY_RUNS)..];
        let mut keys: Vec<(&str, &str)> = Vec::new();
        for run in recent.iter().rev() {
            let shown_rows: Vec<&Measurement> =
                run.measurements.iter().filter(|m| shown(m)).collect();
            for name in first_seen(shown_rows.iter().map(|m| m.name.as_str())) {
                if keys.iter().any(|(n, _)| *n == name) {
                    continue;
                }
                let measured: Vec<&str> = shown_rows
                    .iter()
                    .filter(|m| m.name == name)
                    .map(|m| m.input.as_str())
                    .collect();
                let input = HEADLINE_INPUTS
                    .iter()
                    .find(|h| measured.contains(h))
                    .copied()
                    .unwrap_or(measured[0]);
                keys.push((name, input));
            }
        }
        keys.sort_by_key(|(name, _)| names.iter().position(|n| n == name).unwrap_or(usize::MAX));
        let _ = writeln!(md, "\n### History (GB/s, oldest → newest)\n");
        let mut header = "| Measurement (input) |".to_string();
        let mut rule = "|---|".to_string();
        for run in recent {
            let _ = write!(header, " {} `{}` |", run.label, run.commit);
            rule.push_str("---:|");
        }
        let _ = writeln!(md, "{header}\n{rule}");
        for (name, input) in keys {
            let mut row = format!("| {name} ({input}) |");
            for run in recent {
                let cell = run
                    .measurements
                    .iter()
                    .find(|m| m.name == name && m.input == input)
                    .map_or("—".to_string(), |m| format!("{:.2}", m.gbps));
                let _ = write!(row, " {cell} |");
            }
            let _ = writeln!(md, "{row}");
        }
        let notes: Vec<_> = recent.iter().filter(|r| !r.note.is_empty()).collect();
        if !notes.is_empty() {
            let _ = writeln!(md, "\nWhat changed:\n");
            for r in notes {
                let _ = writeln!(md, "- **{}** `{}`: {}", r.label, r.commit, r.note);
            }
        }
        md.push('\n');
    }
    md
}

/// `1536` → `1.5 KiB`, `268435456` → `256 MiB`.
pub fn human_bytes(bytes: u64) -> String {
    const UNITS: [&str; 4] = ["KiB", "MiB", "GiB", "TiB"];
    if bytes < 1024 {
        return format!("{bytes} B");
    }
    let mut value = bytes as f64;
    let mut unit = "B";
    for u in UNITS {
        if value < 1024.0 {
            break;
        }
        value /= 1024.0;
        unit = u;
    }
    let text = format!("{value:.1}");
    let text = text.strip_suffix(".0").unwrap_or(&text);
    format!("{text} {unit}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::record::{sample_run, Timing};

    fn run(date: &str, label: &str, adapter: &str, rows: &[(&str, f64)]) -> Run {
        Run {
            date: date.into(),
            label: label.into(),
            commit: format!("c-{label}"),
            adapter: adapter.into(),
            measurements: rows
                .iter()
                .map(|&(name, gbps)| Measurement {
                    name: name.into(),
                    gbps,
                    ..sample_run().measurements[0].clone()
                })
                .collect(),
            ..sample_run()
        }
    }

    fn latest_section(md: &str) -> &str {
        let start = md.find("### Latest").expect("latest section");
        let end = md[start..]
            .find("### History")
            .map_or(md.len(), |i| start + i);
        &md[start..end]
    }

    #[test]
    fn human_bytes_uses_binary_units() {
        assert_eq!(human_bytes(100), "100 B");
        assert_eq!(human_bytes(64 << 10), "64 KiB");
        assert_eq!(human_bytes(256 << 20), "256 MiB");
        assert_eq!(human_bytes(3 << 29), "1.5 GiB");
    }

    #[test]
    fn latest_table_shows_newest_runs_numbers() {
        // Out of order on purpose: the newest run is chosen by date.
        let runs = [
            run(
                "2026-10-08T00:00:00Z",
                "M1",
                "GPU A",
                &[("gpu.upload", 20.0)],
            ),
            run(
                "2026-10-07T00:00:00Z",
                "M0",
                "GPU A",
                &[("gpu.upload", 10.0)],
            ),
        ];
        let latest = latest_section(&render(&runs)).to_string();
        assert!(latest.contains("20.00"), "{latest}");
        assert!(!latest.contains("10.00"), "{latest}");
        assert!(latest.contains("M1"), "{latest}");
    }

    #[test]
    fn history_has_a_column_per_run_and_dash_for_missing() {
        let runs = [
            run(
                "2026-10-07T00:00:00Z",
                "M0",
                "GPU A",
                &[("gpu.upload", 10.0)],
            ),
            run(
                "2026-10-08T00:00:00Z",
                "M1",
                "GPU A",
                &[("gpu.upload", 11.0), ("cpu.memcpy", 30.0)],
            ),
        ];
        let md = render(&runs);
        let history = &md[md.find("### History").expect("history section")..];
        let header = history
            .lines()
            .find(|l| l.starts_with("| Measurement"))
            .unwrap();
        assert!(header.contains("M0") && header.contains("M1"), "{header}");
        let memcpy = history.lines().find(|l| l.contains("cpu.memcpy")).unwrap();
        assert!(memcpy.contains("—") && memcpy.contains("30.00"), "{memcpy}");
        let upload = history.lines().find(|l| l.contains("gpu.upload")).unwrap();
        assert!(
            upload.contains("10.00") && upload.contains("11.00"),
            "{upload}"
        );
    }

    #[test]
    fn each_adapter_gets_its_own_section() {
        let runs = [
            run("2026-10-07T00:00:00Z", "M0", "GPU A", &[("x", 1.0)]),
            run("2026-10-07T00:00:00Z", "M0", "GPU B", &[("x", 2.0)]),
        ];
        let md = render(&runs);
        assert!(md.contains("## GPU A") && md.contains("## GPU B"), "{md}");
    }

    #[test]
    fn history_keeps_only_the_most_recent_runs() {
        let runs: Vec<Run> = (0..HISTORY_RUNS + 2)
            .map(|i| {
                run(
                    &format!("2026-10-{:02}T00:00:00Z", i + 1),
                    &format!("R{i}"),
                    "GPU A",
                    &[("x", 1.0)],
                )
            })
            .collect();
        let md = render(&runs);
        let history = &md[md.find("### History").unwrap()..];
        let header = history
            .lines()
            .find(|l| l.starts_with("| Measurement"))
            .unwrap();
        assert!(
            !header.contains("R0 ") && !header.contains("R1 "),
            "{header}"
        );
        assert!(
            header.contains(&format!("R{}", HISTORY_RUNS + 1)),
            "{header}"
        );
    }

    #[test]
    fn history_lists_what_each_run_changed() {
        let mut old = run("2026-10-07T00:00:00Z", "M0", "GPU A", &[("x", 1.0)]);
        old.note = "platform baseline".into();
        let new = run("2026-10-08T00:00:00Z", "M1", "GPU A", &[("x", 2.0)]);
        let md = render(&[old, new]);
        let history = &md[md.find("### History").unwrap()..];
        assert!(
            history.contains("- **M0** `c-M0`: platform baseline"),
            "{history}"
        );
        // Runs without a note aren't listed.
        assert!(!history.contains("- **M1**"), "{history}");
    }

    fn on(name: &str, input: &str, gbps: f64) -> Measurement {
        Measurement {
            name: name.into(),
            input: input.into(),
            gbps,
            ..sample_run().measurements[0].clone()
        }
    }

    fn with(rows: Vec<Measurement>) -> Run {
        Run {
            measurements: rows,
            ..run("2026-10-07T00:00:00Z", "M1", "GPU A", &[])
        }
    }

    #[test]
    fn per_file_corpus_rows_are_left_out() {
        let md = render(&[with(vec![
            on("cpu.x", "silesia/dickens", 1.0),
            on("cpu.x", "silesia/all", 2.0),
        ])]);
        assert!(!md.contains("silesia/dickens"), "{md}");
        assert!(md.contains("silesia/all"), "{md}");
    }

    #[test]
    fn latest_table_is_a_measurement_by_input_matrix() {
        let md = render(&[with(vec![
            on("cpu.x", "text", 1.0),
            on("cpu.x", "zeros", 2.0),
            on("cpu.y", "text", 3.0),
        ])]);
        let latest = latest_section(&md);
        assert!(
            latest.contains("| Measurement | text | zeros |"),
            "{latest}"
        );
        let x_rows: Vec<_> = latest
            .lines()
            .filter(|l| l.starts_with("| cpu.x"))
            .collect();
        assert_eq!(x_rows.len(), 1, "{latest}");
        assert!(
            x_rows[0].contains("1.00") && x_rows[0].contains("2.00"),
            "{latest}"
        );
        let y_row = latest.lines().find(|l| l.starts_with("| cpu.y")).unwrap();
        assert!(y_row.contains("3.00") && y_row.contains("—"), "{y_row}");
    }

    #[test]
    fn history_tracks_one_headline_input_per_measurement() {
        let md = render(&[with(vec![
            on("cpu.x", "text", 1.0),
            on("cpu.x", "silesia/all", 2.0),
            on("cpu.y", "random", 3.0),
        ])]);
        let history = &md[md.find("### History").unwrap()..];
        let rows: Vec<_> = history
            .lines()
            .filter(|l| l.starts_with("| cpu."))
            .collect();
        assert_eq!(rows.len(), 2, "{history}");
        assert!(rows[0].starts_with("| cpu.x (silesia/all)") && rows[0].contains("2.00"));
        assert!(rows[1].starts_with("| cpu.y (random)") && rows[1].contains("3.00"));
    }

    #[test]
    fn ratio_is_shown_when_present() {
        let mut r = run("2026-10-07T00:00:00Z", "M1", "GPU A", &[("cpu.lz4", 1.0)]);
        r.measurements[0].ratio = Some(2.345);
        r.measurements[0].timing = Timing::Cpu;
        let latest = latest_section(&render(&[r])).to_string();
        assert!(latest.contains("2.35×"), "{latest}");
    }
}
