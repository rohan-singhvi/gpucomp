//! Renders `bench/REPORT.md` (M10): a hand-written template whose `{{name}}`
//! placeholders are filled with tables from the newest corpus run of each
//! adapter. The prose lives in the template; every number comes from
//! `bench/results/*.json`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::record::{Measurement, Run, Timing};
use crate::report::human_bytes;

/// The placeholders a template can use, as `{{name}}`.
pub const SECTIONS: [&str; 11] = [
    "setup",
    "versus",
    "compress",
    "decompress",
    "files-compress",
    "files-decompress",
    "synthetic-compress",
    "synthetic-decompress",
    "numeric",
    "profile",
    "platform",
];

/// Fills `template`'s placeholders from `runs`: per adapter, the newest run
/// that measured a corpus (else its newest run). With several adapters, each
/// section repeats per adapter under its name.
pub fn render(runs: &[Run], template: &str) -> anyhow::Result<String> {
    let runs = select(runs);
    anyhow::ensure!(!runs.is_empty(), "no recorded runs to report");
    let mut md = String::from(
        "<!-- Generated by `gpucomp bench --report` from bench/REPORT.template.md and \
         bench/results/*.json; edit the template, not this file. -->\n\n",
    );
    let mut rest = template;
    while let Some(start) = rest.find("{{") {
        md.push_str(&rest[..start]);
        let len = rest[start..]
            .find("}}")
            .ok_or_else(|| anyhow::anyhow!("unclosed placeholder in the template"))?;
        let name = rest[start + 2..start + len].trim();
        anyhow::ensure!(
            SECTIONS.contains(&name),
            "unknown placeholder {{{{{name}}}}}; known: {}",
            SECTIONS.join(", ")
        );
        let parts: Vec<String> = runs
            .iter()
            .map(|run| {
                let body = section(name, run);
                if runs.len() > 1 {
                    format!("**{}** ({})\n\n{body}", run.adapter, run.backend)
                } else {
                    body
                }
            })
            .collect();
        md.push_str(parts.join("\n\n").trim_end());
        rest = &rest[start + len + 2..];
    }
    md.push_str(rest);
    Ok(md)
}

/// Per adapter (by name), the newest run that measured a corpus, else the
/// newest run.
fn select(runs: &[Run]) -> Vec<&Run> {
    let key = |r: &Run| {
        (
            r.measurements.iter().any(|m| m.input.contains('/')),
            r.date.clone(),
        )
    };
    let mut best: BTreeMap<&str, &Run> = BTreeMap::new();
    for run in runs {
        let slot = best.entry(&run.adapter).or_insert(run);
        if key(run) > key(slot) {
            *slot = run;
        }
    }
    best.into_values().collect()
}

/// The compression ratio-vs-throughput table for `run`, if it measured any
/// encoder (also shown in `BENCHMARKS.md`).
pub fn compress_tradeoff(run: &Run) -> Option<String> {
    tradeoff(run, "Encoder", COMPRESS)
}

fn section(name: &str, run: &Run) -> String {
    let body = match name {
        "setup" => setup(run),
        "versus" => versus(run),
        "compress" => compress_tradeoff(run),
        "decompress" => tradeoff(run, "Decoder", DECOMPRESS),
        "files-compress" => matrix(run, &corpus_inputs(run), &FILE_COMPRESS),
        "files-decompress" => matrix(run, &corpus_inputs(run), &FILE_DECOMPRESS),
        "synthetic-compress" => matrix(run, &SYNTHETIC, &FILE_COMPRESS),
        "synthetic-decompress" => matrix(run, &SYNTHETIC, &FILE_DECOMPRESS),
        "numeric" => matrix(run, &NUMERIC, &NUMERIC_COLUMNS),
        "profile" => profile(run),
        "platform" => platform(run),
        _ => unreachable!("checked against SECTIONS"),
    };
    body.unwrap_or_else(|| "_Not measured in this run._".into())
}

fn find<'a>(run: &'a Run, name: &str, input: &str) -> Option<&'a Measurement> {
    run.measurements
        .iter()
        .find(|m| m.name == name && m.input == input)
}

/// The input most tables describe: a corpus's concatenation, else `text`,
/// else the first input measured.
fn headline(run: &Run) -> Option<&str> {
    let inputs = || run.measurements.iter().map(|m| m.input.as_str());
    inputs()
        .find(|i| i.ends_with("/all"))
        .or_else(|| inputs().find(|&i| i == "text"))
        .or_else(|| inputs().next())
}

/// Corpus inputs (`corpus/file`) in the order measured, concatenations last.
fn corpus_inputs(run: &Run) -> Vec<&str> {
    let mut files: Vec<&str> = Vec::new();
    for m in &run.measurements {
        if m.input.contains('/') && !files.contains(&m.input.as_str()) {
            files.push(&m.input);
        }
    }
    files.sort_by_key(|i| i.ends_with("/all"));
    files
}

fn input_note(run: &Run, input: &str) -> String {
    let size = run
        .measurements
        .iter()
        .find(|m| m.input == input)
        .map_or(String::new(), |m| format!(" ({})", human_bytes(m.bytes)));
    format!("Input: `{input}`{size}.\n\n")
}

fn ms(m: &Measurement) -> f64 {
    m.bytes as f64 / (m.gbps * 1e9) * 1e3
}

fn ratio(r: Option<f64>) -> String {
    r.map_or("—".into(), |r| format!("{r:.2}×"))
}

fn setup(run: &Run) -> Option<String> {
    let timestamps = run
        .measurements
        .iter()
        .any(|m| m.timing == Timing::GpuTimestamp);
    let kernel_timing = if timestamps {
        "GPU timestamps"
    } else {
        "wall clock of submit + wait, data on the GPU (no timestamps)"
    };
    let cpu = if run.cpu.is_empty() { "—" } else { &run.cpu };
    Some(format!(
        "| Adapter | Backend | Host CPU | OS | Run | Commit | Date | GPU kernel timing |\n\
         |---|---|---|---|---|---|---|---|\n\
         | {} | {} | {cpu} | {} | {} | `{}` | {} | {kernel_timing} |",
        run.adapter, run.backend, run.os, run.label, run.commit, run.date
    ))
}

fn platform(run: &Run) -> Option<String> {
    let rows: Vec<String> = [
        ("cpu.memcpy", "CPU memcpy"),
        ("gpu.upload", "Upload, host to GPU"),
        ("gpu.readback", "Readback, GPU to host"),
        ("gpu.xor.kernel", "Trivial kernel (XOR), data on the GPU"),
        ("gpu.xor.e2e", "Trivial kernel, end to end"),
    ]
    .iter()
    .filter_map(|(name, label)| {
        let m = run.measurements.iter().find(|m| m.name == *name)?;
        Some(format!("| {label} | {:.2} |", m.gbps))
    })
    .collect();
    (!rows.is_empty()).then(|| format!("| Measurement | GB/s |\n|---|---:|\n{}", rows.join("\n")))
}

