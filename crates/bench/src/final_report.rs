/// One row per input that has any of `columns`, one cell per column.
fn matrix(run: &Run, inputs: &[&str], columns: &[Column]) -> Option<String> {
    let mut md = String::new();
    for input in inputs {
        let cells: Vec<Option<&Measurement>> =
            columns.iter().map(|c| find(run, c.row, input)).collect();
        if cells.iter().all(Option::is_none) {
            continue;
        }
        let size = run
            .measurements
            .iter()
            .find(|m| m.input == *input)
            .map_or(String::new(), |m| human_bytes(m.bytes));
        let _ = write!(md, "| {input} | {size} |");
        for (c, m) in columns.iter().zip(cells) {
            let cell = match (m, c.cell) {
                (None, _) => "—".into(),
                (Some(m), Cell::Ratio) => ratio(m.ratio),
                (Some(m), Cell::Gbps) => format!("{:.2}", m.gbps),
                (Some(m), Cell::Both) => format!("{} · {:.2}", ratio(m.ratio), m.gbps),
            };
            let _ = write!(md, " {cell} |");
        }
        md.push('\n');
    }
    if md.is_empty() {
        return None;
    }
    let labels: Vec<&str> = columns.iter().map(|c| c.label).collect();
    Some(format!(
        "| Input | Size | {} |\n|---|---:|{}\n{md}",
        labels.join(" | "),
        "---:|".repeat(columns.len())
    ))
}

