/// Each profiled path's stages (consecutive prefix times subtracted), then
/// the rest of its end-to-end time, with shares of end to end.
fn profile(run: &Run) -> Option<String> {
    let input = headline(run)?;
    let mut md = String::new();
    for (prefix, label, e2e) in PROFILES {
        let marker = format!("{prefix}.upto.");
        let prefixes: Vec<(&str, f64)> = run
            .measurements
            .iter()
            .filter(|m| m.input == input)
            .filter_map(|m| Some((m.name.strip_prefix(&marker)?, ms(m))))
            .collect();
        if prefixes.is_empty() {
            continue;
        }
        let kernels = prefixes[prefixes.len() - 1].1;
        let total = find(run, e2e, input).map_or(kernels, ms);
        let mut first = true;
        let mut line = |stage: &str, time: f64, bold: bool| {
            let path = if std::mem::take(&mut first) {
                label
            } else {
                ""
            };
            let share = 100.0 * time / total;
            let (stage, time) = if bold {
                (format!("**{stage}**"), format!("**{time:.1}**"))
            } else {
                (stage.to_string(), format!("{time:.1}"))
            };
            let _ = writeln!(md, "| {path} | {stage} | {time} | {share:.0}% |");
        };
        let mut previous = 0.0;
        for (stage, t) in &prefixes {
            line(stage, (t - previous).max(0.0), false);
            previous = *t;
        }
        if find(run, e2e, input).is_some() {
            line("transfers and host work", (total - kernels).max(0.0), false);
            line("end to end", total, true);
        }
    }
    (!md.is_empty()).then(|| {
        format!(
            "{}| Path | Stage | ms | Share |\n|---|---|---:|---:|\n{md}",
            input_note(run, input)
        )
    })
}

