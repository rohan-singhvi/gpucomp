/// Which `(ratio, throughput)` points no other point beats on both axes
/// (at least as good on both and better on one).
fn pareto(points: &[(f64, f64)]) -> Vec<bool> {
    points
        .iter()
        .map(|&(r, t)| {
            !points
                .iter()
                .any(|&(r2, t2)| r2 >= r && t2 >= t && (r2 > r || t2 > t))
        })
        .collect()
}

/// Ratio against end-to-end throughput on the headline input, fastest first,
/// with the Pareto frontier marked.
fn tradeoff(run: &Run, what: &str, paths: &[Path]) -> Option<String> {
    let input = headline(run)?;
    let rows: Vec<(&str, f64, Option<f64>, f64)> = paths
        .iter()
        .filter_map(|p| {
            let e2e = find(run, p.e2e, input)?;
            let kernel = p
                .e2e
                .strip_suffix(".e2e")
                .and_then(|stem| find(run, &format!("{stem}.kernel"), input))
                .map(|m| m.gbps);
            Some((p.label, e2e.ratio?, kernel, e2e.gbps))
        })
        .collect();
    if rows.is_empty() {
        return None;
    }
    let frontier = pareto(&rows.iter().map(|r| (r.1, r.3)).collect::<Vec<_>>());
    let mut order: Vec<usize> = (0..rows.len()).collect();
    order.sort_by(|&a, &b| rows[b].3.total_cmp(&rows[a].3));
    let mut md = input_note(run, input);
    let _ = writeln!(
        md,
        "| {what} | Ratio | GPU kernel GB/s | End-to-end GB/s | Pareto |\n|---|---:|---:|---:|:---:|"
    );
    for k in order {
        let (label, r, kernel, e2e) = rows[k];
        let kernel = kernel.map_or("—".into(), |g| format!("{g:.2}"));
        let mark = if frontier[k] { "◆" } else { "" };
        let _ = writeln!(md, "| {label} | {r:.2}× | {kernel} | {e2e:.2} | {mark} |");
    }
    Some(md)
}

/// What a matrix cell shows.
