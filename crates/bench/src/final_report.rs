fn versus(run: &Run) -> Option<String> {
    let input = headline(run)?;
    let rows: Vec<String> = VERSUS
        .iter()
        .filter_map(|&(label, gpu, cpu)| {
            let (g, c) = (find(run, gpu, input)?, find(run, cpu, input)?);
            let kernel = gpu
                .strip_suffix(".e2e")
                .and_then(|stem| find(run, &format!("{stem}.kernel"), input))
                .map_or("—".into(), |m| format!("{:.2}", m.gbps));
            Some(format!(
                "| {label} | {} · {} | {kernel} | {:.2} | {:.2} | {:.2}× |",
                ratio(g.ratio),
                ratio(c.ratio),
                g.gbps,
                c.gbps,
                g.gbps / c.gbps
            ))
        })
        .collect();
    (!rows.is_empty()).then(|| {
        format!(
            "{}| Comparison | Ratio, GPU · CPU | GPU kernel GB/s | GPU end-to-end GB/s | CPU GB/s | GPU ÷ CPU |\n\
             |---|---:|---:|---:|---:|---:|\n{}",
            input_note(run, input),
            rows.join("\n")
        )
    })
}

